import Testing
@testable import BentoCore

private func clip(_ text: String, at time: Double, app: String? = "Safari", kind: ClipKind = .text, secret: Bool = false) -> ClipEntry {
    ClipEntry(key: "k:\(text)", kind: kind, text: text, app: app, at: time, secret: secret)
}

private func texts(_ h: ClipboardHistory) -> [String] {
    h.entries.map(\.text)
}

@Suite struct ClipboardHistoryTests {
    @Test func newestCopyGoesOnTop() {
        var h = ClipboardHistory(limit: 200)
        h.record(clip("first", at: 1))
        h.record(clip("second", at: 2))
        #expect(texts(h) == ["second", "first"])
    }

    @Test func recopyUpdatesCountAndTimes() {
        var h = ClipboardHistory(limit: 200)
        h.record(clip("a", at: 1, app: "Safari"))
        h.record(clip("b", at: 2))
        h.record(clip("a", at: 5, app: "Notes"))
        #expect(texts(h) == ["a", "b"])
        let a = h.entries[0]
        #expect(a.copies == 2)
        #expect(a.firstCopied == 1)
        #expect(a.lastCopied == 5)
        #expect(a.app == "Notes")
    }

    @Test func touchMovesToTopWithoutCounting() {
        var h = ClipboardHistory(limit: 200)
        h.record(clip("a", at: 1))
        h.record(clip("b", at: 2))
        h.touch("k:a", at: 3)
        #expect(texts(h) == ["a", "b"])
        #expect(h.entries[0].copies == 1)
    }

    @Test func blankTextIsIgnored() {
        var h = ClipboardHistory(limit: 200)
        h.record(clip("kept", at: 1))
        h.record(clip("", at: 2))
        h.record(clip("  \n\t ", at: 3))
        #expect(texts(h) == ["kept"])
    }

    @Test func imageWithoutTextIsKept() {
        var h = ClipboardHistory(limit: 200)
        h.record(clip("", at: 1, kind: .image))
        #expect(h.entries.count == 1)
    }

    @Test func pinnedStayOnTopAndSurviveLimit() {
        var h = ClipboardHistory(limit: 3)
        h.record(clip("old", at: 1))
        h.togglePin("k:old")
        for i in 2...5 { h.record(clip("\(i)", at: Double(i))) }
        #expect(texts(h) == ["old", "5", "4", "3"])
        #expect(h.entries[0].pinned)
    }

    @Test func unpinReturnsToRecencyOrder() {
        var h = ClipboardHistory(limit: 200)
        h.record(clip("a", at: 1))
        h.record(clip("b", at: 2))
        h.record(clip("c", at: 3))
        h.togglePin("k:a")
        #expect(texts(h) == ["a", "c", "b"])
        h.togglePin("k:a")
        #expect(texts(h) == ["c", "b", "a"])
    }

    @Test func limitEvictsOldestUnpinnedAndReturnsKeys() {
        var h = ClipboardHistory(limit: 200)
        var evicted: [String] = []
        for i in 1...201 { evicted += h.record(clip("\(i)", at: Double(i))) }
        #expect(h.entries.count == 200)
        #expect(h.entries.first?.text == "201")
        #expect(h.entries.last?.text == "2")
        #expect(evicted == ["k:1"])
    }

    @Test func shrinkingLimitEvictsAndReturnsKeys() {
        var h = ClipboardHistory(limit: 200)
        for i in 1...6 { h.record(clip("\(i)", at: Double(i))) }
        h.togglePin("k:1")
        let removed = h.setLimit(3)
        #expect(Set(removed) == ["k:2", "k:3"])
        #expect(texts(h) == ["1", "6", "5", "4"])
        #expect(h.limit == 3)
        #expect(h.setLimit(10) == [])
    }

    @Test func removeAndClearReturnRemovedKeys() {
        var h = ClipboardHistory(limit: 200)
        for (i, t) in ["a", "b", "c", "d"].enumerated() { h.record(clip(t, at: Double(i))) }
        h.togglePin("k:b")
        #expect(h.remove("k:c") == ["k:c"])
        #expect(h.remove("nope") == [])
        #expect(Set(h.clear()) == ["k:a", "k:d"])
        #expect(texts(h) == ["b"])
    }

    @Test func relativeTimeLabels() {
        #expect(relativeTime(0) == "now")
        #expect(relativeTime(59) == "now")
        #expect(relativeTime(5 * 60 + 10) == "5m")
        #expect(relativeTime(3 * 3600 + 100) == "3h")
        #expect(relativeTime(2 * 86400 + 5) == "2d")
    }

    @Test func concealedIsRecordedAsSecret() {
        #expect(clipCapture(types: ["public.utf8-plain-text"], text: "hello") == .normal)
        #expect(clipCapture(types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"], text: "hunter2") == .secret)
        #expect(clipCapture(types: ["org.nspasteboard.TransientType", "public.utf8-plain-text"], text: "x") == .skip)
        #expect(clipCapture(types: ["public.utf8-plain-text", "org.nspasteboard.AutoGeneratedType"], text: "x") == .skip)
    }

    @Test func secretHeuristics() {
        let secrets = [
            "sk-proj-abcdefghijklmnopqrstuvwxyz012345",
            "ghp_abcdefghijklmnopqrstuvwxyz0123456789",
            "github_pat_11ABCDEFG0123456789_abcdefghijklmnop",
            "xoxb-" + "123456789012-abcdefghijklmnop",
            "AKIAIOSFODNN7EXAMPLE",
            "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0In0.dBjftJeZ4CVPmB92K27uhbUJU1p1r_wW1gFWFOEjXk",
            "-----BEGIN OPENSSH PRIVATE KEY-----\nb3BlbnNzaC1rZXk\n-----END OPENSSH PRIVATE KEY-----",
            "  ghp_abcdefghijklmnopqrstuvwxyz0123456789\n",
        ]
        let plain = [
            "hello world", "sk-", "skip this", "eyJ not a token", "AKIA short", "git push origin main",
            "https://github.com/anthropics", "ghp_short",
        ]
        for s in secrets { #expect(looksLikeSecret(s), "\(s)") }
        for s in plain { #expect(!looksLikeSecret(s), "\(s)") }
        #expect(clipCapture(types: ["public.utf8-plain-text"], text: secrets[0]) == .secret)
    }

    @Test func secretIsMaskedHiddenFromSearchAndNotPersisted() {
        var h = ClipboardHistory(limit: 200)
        h.record(clip("hunter2", at: 1, app: "1Password", secret: true))
        h.record(clip("hunter reading", at: 2))
        #expect(h.entries.first { $0.secret }?.displayText == "••••••••")
        #expect(h.entries.first { !$0.secret }?.displayText == "hunter reading")
        #expect(h.matching("hunter").map(\.text) == ["hunter reading"])
        #expect(h.matching("1password").count == 1)
        #expect(h.persistable.map(\.text) == ["hunter reading"])
    }

    @Test func searchMatchesAppAndFilePaths() {
        var h = ClipboardHistory(limit: 200)
        h.record(clip("", at: 1, app: "Safari", kind: .image))
        h.record(clip("/Users/me/Desktop/Report.pdf", at: 2, app: "Finder", kind: .files))
        h.record(clip("xABCx", at: 3, app: "Notes"))
        #expect(h.matching("safari").map(\.kind) == [.image])
        #expect(h.matching("report").map(\.kind) == [.files])
        #expect(h.matching("abc").map(\.text) == ["xABCx"])
        #expect(h.matching("").count == 3)
    }

    @Test func selectionStaysWithinList() {
        #expect(clampedSelection(-1, count: 3) == 0)
        #expect(clampedSelection(1, count: 3) == 1)
        #expect(clampedSelection(3, count: 3) == 2)
        #expect(clampedSelection(2, count: 0) == 0)
    }
}
