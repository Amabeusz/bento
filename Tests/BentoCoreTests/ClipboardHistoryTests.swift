import Testing
@testable import BentoCore

@Suite struct ClipboardHistoryTests {
    @Test func newestCopyGoesOnTop() {
        var h = ClipboardHistory(limit: 200)
        h.record("first")
        h.record("second")
        #expect(h.entries == ["second", "first"])
    }

    @Test func copyingAgainMovesEntryToTopWithoutDuplicate() {
        var h = ClipboardHistory(limit: 200)
        h.record("a")
        h.record("b")
        h.record("a")
        #expect(h.entries == ["a", "b"])
    }

    @Test func oldestEntryDropsPastLimit() {
        var h = ClipboardHistory(limit: 200)
        for i in 1...201 { h.record("\(i)") }
        #expect(h.entries.count == 200)
        #expect(h.entries.first == "201")
        #expect(h.entries.last == "2")
    }

    @Test func blankTextIsIgnored() {
        var h = ClipboardHistory(limit: 200)
        h.record("kept")
        h.record("")
        h.record("  \n\t ")
        #expect(h.entries == ["kept"])
    }

    @Test func skipsConcealedAndTransientTypes() {
        #expect(isRecordable(types: ["public.utf8-plain-text"]))
        #expect(!isRecordable(types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]))
        #expect(!isRecordable(types: ["org.nspasteboard.TransientType", "public.utf8-plain-text"]))
        #expect(!isRecordable(types: ["public.utf8-plain-text", "org.nspasteboard.AutoGeneratedType"]))
    }

    @Test func queryFiltersCaseInsensitivelyInHistoryOrder() {
        var h = ClipboardHistory(limit: 200)
        for t in ["xABCx", "other", "abc", "zzz Abc"] { h.record(t) }
        #expect(h.matching("abc") == ["zzz Abc", "abc", "xABCx"])
        #expect(h.matching("") == ["zzz Abc", "abc", "other", "xABCx"])
        #expect(h.matching("nope").isEmpty)
    }

    @Test func selectionStaysWithinList() {
        #expect(clampedSelection(-1, count: 3) == 0)
        #expect(clampedSelection(1, count: 3) == 1)
        #expect(clampedSelection(3, count: 3) == 2)
        #expect(clampedSelection(2, count: 0) == 0)
    }
}
