public enum ClipKind: String, Codable, Sendable {
    case text, image, files
}

public enum ClipCapture: Equatable, Sendable {
    case skip, normal, secret
}

public let maskedSecret = "••••••••"

public struct ClipEntry: Codable, Equatable, Sendable {
    public var key: String
    public var kind: ClipKind
    public var text: String
    public var app: String?
    public var firstCopied: Double
    public var lastCopied: Double
    public var copies: Int
    public var pinned: Bool
    public var secret: Bool

    public init(key: String, kind: ClipKind = .text, text: String, app: String? = nil, at time: Double, secret: Bool = false) {
        self.key = key
        self.kind = kind
        self.text = text
        self.app = app
        firstCopied = time
        lastCopied = time
        copies = 1
        pinned = false
        self.secret = secret
    }

    public var displayText: String { secret ? maskedSecret : text }
}

public struct ClipboardHistory: Equatable, Sendable {
    public private(set) var entries: [ClipEntry]
    public private(set) var limit: Int

    public init(limit: Int, entries: [ClipEntry] = []) {
        self.limit = limit
        self.entries = entries
        _ = arrange()
    }

    @discardableResult
    public mutating func record(_ e: ClipEntry) -> [String] {
        guard e.kind != .text || !e.text.allSatisfy(\.isWhitespace) else { return [] }
        if let i = entries.firstIndex(where: { $0.key == e.key }) {
            entries[i].lastCopied = e.lastCopied
            entries[i].copies += 1
            entries[i].app = e.app ?? entries[i].app
            entries[i].secret = entries[i].secret || e.secret
        } else {
            entries.append(e)
        }
        return arrange()
    }

    public mutating func touch(_ key: String, at time: Double) {
        guard let i = entries.firstIndex(where: { $0.key == key }) else { return }
        entries[i].lastCopied = time
        _ = arrange()
    }

    public mutating func setLimit(_ limit: Int) -> [String] {
        self.limit = limit
        return arrange()
    }

    public mutating func togglePin(_ key: String) {
        guard let i = entries.firstIndex(where: { $0.key == key }) else { return }
        entries[i].pinned.toggle()
        _ = arrange()
    }

    public mutating func remove(_ key: String) -> [String] {
        guard let i = entries.firstIndex(where: { $0.key == key }) else { return [] }
        return [entries.remove(at: i).key]
    }

    public mutating func clear() -> [String] {
        let removed = entries.filter { !$0.pinned }.map(\.key)
        entries.removeAll { !$0.pinned }
        return removed
    }

    public func matching(_ query: String) -> [ClipEntry] {
        guard !query.isEmpty else { return entries }
        let q = query.lowercased()
        return entries.filter { e in
            (!e.secret && e.text.lowercased().contains(q)) || (e.app?.lowercased().contains(q) ?? false)
        }
    }

    public var persistable: [ClipEntry] { entries.filter { !$0.secret } }

    private mutating func arrange() -> [String] {
        entries.sort { a, b in a.pinned != b.pinned ? a.pinned : a.lastCopied > b.lastCopied }
        var unpinned = 0
        var evicted: [String] = []
        entries.removeAll { e in
            guard !e.pinned else { return false }
            unpinned += 1
            if unpinned > limit { evicted.append(e.key); return true }
            return false
        }
        return evicted
    }
}

private let skippedTypes: Set<String> = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
public let concealedType = "org.nspasteboard.ConcealedType"

public func clipCapture(types: [String], text: String?) -> ClipCapture {
    if !skippedTypes.isDisjoint(with: types) { return .skip }
    if types.contains(concealedType) || text.map(looksLikeSecret) == true { return .secret }
    return .normal
}

private let tokenPrefixes = [
    "sk-", "sk_live_", "sk_test_", "rk_live_", "ghp_", "gho_", "ghs_", "ghu_", "github_pat_",
    "xoxb-", "xoxp-", "xoxa-", "glpat-",
]

public func looksLikeSecret(_ text: String) -> Bool {
    if text.contains("-----BEGIN"), text.contains("PRIVATE KEY-----") { return true }
    let token = String(text.drop(while: \.isWhitespace).reversed().drop(while: \.isWhitespace).reversed())
    guard !token.contains(where: \.isWhitespace) else { return false }
    if token.count >= 20, tokenPrefixes.contains(where: token.hasPrefix) { return true }
    if token.count == 20, token.hasPrefix("AKIA"), token.allSatisfy({ $0.isUppercase || $0.isNumber }) { return true }
    let parts = token.split(separator: ".", omittingEmptySubsequences: false)
    return token.hasPrefix("eyJ") && parts.count == 3 && parts.allSatisfy { $0.count >= 8 }
}

public func relativeTime(_ seconds: Double) -> String {
    switch seconds {
    case ..<60: "now"
    case ..<3600: "\(Int(seconds / 60))m"
    case ..<86400: "\(Int(seconds / 3600))h"
    default: "\(Int(seconds / 86400))d"
    }
}

public func clampedSelection(_ index: Int, count: Int) -> Int {
    max(0, min(index, count - 1))
}
