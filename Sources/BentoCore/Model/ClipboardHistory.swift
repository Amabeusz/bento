public struct ClipboardHistory: Equatable, Sendable {
    public private(set) var entries: [String]
    public let limit: Int

    public init(limit: Int, entries: [String] = []) {
        self.limit = limit
        self.entries = Array(entries.prefix(limit))
    }

    public mutating func record(_ text: String) {
        guard !text.allSatisfy(\.isWhitespace) else { return }
        entries.removeAll { $0 == text }
        entries.insert(text, at: 0)
        if entries.count > limit { entries.removeLast(entries.count - limit) }
    }

    public func matching(_ query: String) -> [String] {
        query.isEmpty ? entries : entries.filter { $0.lowercased().contains(query.lowercased()) }
    }
}

private let skippedTypes: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
]

public func isRecordable(types: [String]) -> Bool {
    skippedTypes.isDisjoint(with: types)
}

public func clampedSelection(_ index: Int, count: Int) -> Int {
    max(0, min(index, count - 1))
}
